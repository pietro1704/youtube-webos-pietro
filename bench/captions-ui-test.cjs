const assert = require('node:assert/strict');
const { boot } = require('./dependency-test.cjs');
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
(async () => {
  const { win } = boot({ enablePersistentCaptions: false, enableLegacyEmojiFix: false, dearrowMode: 'off' });
  try {
    let id = 'aaaaaaaaaaa';
    let style = { fontSizeIncrement: 0, color: '#ffffff', fontStyle: 0 };
    let actual = {};
    let tracks = [{ languageCode: 'en', languageName: 'English', is_translateable: true }, { languageCode: 'pt', languageName: 'Portuguese' }];
    const calls = [];
    const p = win.document.createElement('div'); p.id = 'ytlr-player__player-container-player';
    p.getVideoData = () => ({ video_id: id });
    p.getSubtitlesUserSettings = () => ({ ...style });
    p.updateSubtitlesUserSettings = value => { style = { ...value }; calls.push(['style', value]); };
    p.getOption = (_module, key) => key === 'tracklist' ? tracks : key === 'track' ? actual : [{ languageCode: 'es', languageName: 'Spanish' }];
    p.setOption = (_module, _key, value) => { actual = value; calls.push(['track', value]); };
    p.loadModule = () => {};
    win.document.querySelector('ytlr-app').appendChild(p);
    win.document.body.className = 'WEB_PAGE_TYPE_WATCH'; await wait(30);
    win.ytaf_showOptionsPanel(true);
    const checkbox = label => Array.from(win.document.querySelectorAll('label')).find(el => el.textContent.includes(label)).querySelector('input');
    const row = label => Array.from(win.document.querySelectorAll('.shortcut-control-row')).find(el => el.textContent.includes(label));
    checkbox('Persistent captions').click(); await wait(160);
    row('Caption language').click(); row('Caption language').click(); row('Caption language').click();
    row('Caption size').click(); row('Caption style').click(); row('Caption style').click();
    await wait(160);
    assert.equal(actual.languageCode, 'pt'); assert.equal(style.fontSizeIncrement, -2); assert.equal(style.color, '#ffff00');
    checkbox('Offer available automatic translations').click(); row('Caption language').click(); await wait(160);
    assert.equal(actual.translationLanguage.languageCode, 'es');
    await wait(220);
    const saved = JSON.parse(win.localStorage.getItem('ytaf-configuration'));
    assert.equal(saved.captionLanguage, 'es'); assert.equal(saved.captionSavedStyle.color, '#ffffff');
    const priorTracks = calls.filter(call => call[0] === 'track').length;
    id = 'bbbbbbbbbbb'; tracks = [{ languageCode: 'fr', is_translateable: false }]; actual = {}; style = { fontSizeIncrement: 0 };
    win.dispatchEvent(new win.CustomEvent('ytaf-page-update', { detail: { isWatch: true } })); await wait(160);
    assert.equal(calls.filter(call => call[0] === 'track').length, priorTracks);
    assert.match(win.document.getElementById('ytaf-caption-controls').textContent, /unavailable for this video/);
    checkbox('Persistent captions').click();
    const before = calls.length; row('Caption size').click(); await wait(160); assert.equal(calls.length, before);
    id = 'ccccccccccc'; tracks = [{ languageCode: 'en', is_translateable: true }]; actual = {};
    const trackCount = calls.filter(call => call[0] === 'track').length;
    p.setOption = (_module, _key, value) => { calls.push(['track', value]); win.setTimeout(() => { actual = value; }, 700); };
    checkbox('Persistent captions').click(); await wait(1350);
    assert.equal(calls.filter(call => call[0] === 'track').length, trackCount + 1, 'slow caption loading must not be restarted by polling');
    assert.equal(actual.translationLanguage.languageCode, 'es');
    let loaded = false, loads = 0; id = 'ddddddddddd'; actual = {};
    const readOption = p.getOption;
    p.getOption = (module, key, arg) => key === 'tracklist' && !loaded ? [] : readOption(module, key, arg);
    p.getSubtitlesUserSettings = () => loaded ? { ...style } : null;
    p.loadModule = () => { loaded = true; loads++; };
    win.dispatchEvent(new win.CustomEvent('ytaf-page-update', { detail: { isWatch: true } }));
    await wait(1350); assert.equal(loads, 1, 'load native captions for a saved language on the next video');
    assert.equal(actual.translationLanguage.languageCode, 'es');
    console.log('captions UI: native language, size/style, offered translation, saved defaults and missing-track/disabled fallback passed');
  } finally { win.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
